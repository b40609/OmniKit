def clean(text):
    """自由填寫的文字收成一行，去掉開頭的 Markdown 符號，避免變成新的標題或清單。"""
    return re.sub(r"\s+", " ", text or "").strip().lstrip("#>-*` ").strip()


def check_answers(answers):
    errors = validate.schema_errors(validate.validator("answers.schema.json"), answers, Path("答案"))
    if not errors and answers["verbosity"] == "detailed" and "too-long" in answers["pains"]:
        errors.append("「回覆可以詳細」跟「回覆太長」互相矛盾，請改其中一個")
    return errors


def normalize(answers):
    a = dict(answers)
    if "background" in a:
        a["background"] = clean(a["background"])
        if not a["background"]:
            del a["background"]
    if "projects" in a:
        a["projects"] = {k: clean(v) for k, v in a["projects"].items()}
    return a


def render_rules(a, today):
    t = TEXT[a["language"]]
    out = [t["title"].format(name=a["name"]), "", t["profile"].format(name=a["name"]), "",
           t["note"].format(date=today)]

    def section(title, lines):
        if lines:
            out.extend(["", title, *(f"- {line}" for line in lines)])

    section(t["lang_h"], [t["lang"]])
    comm = [t[a["verbosity"]]]
    if "too-long" in a["pains"]:
        comm.append(t["pains"]["too-long"])
    section(t["comm_h"], [*comm, t["cite"]])
    habits = [t["work"][w] for w in WORK_ORDER if w in a["work"]]
    habits += [t["pains"][p] for p in ("scope-creep", "no-verification", "guesses") if p in a["pains"]]
    section(t["work_h"], habits)
    if a.get("background"):
        section(t["bg_h"], [t["bg"].format(background=a["background"])])
    section(t["confirm_h"], t["autonomy"][a["autonomy"]])
    section(t["git_h"], t["git"])
    return "\n".join(out) + "\n"


def render_scenarios(a, slots):
    """評估工具時用的情境：把範本裡的 <你的專案> 換成真實專案；沒有佔位的槽位沿用範本，不列。"""
    if not a["evaluate_tools"]:
        return None
    names = {"main": a["projects"]["main"], "frontend": a["projects"].get("frontend") or a["projects"]["main"]}
    out = {}
    for slot in slots:
        texts = [s["text"] for s in slot["scenarios"]]
        if not any(mark in text for text in texts for mark, _ in PLACEHOLDERS):
            continue
        items = []
        for s in slot["scenarios"]:
            text = s["text"]
            for mark, key in PLACEHOLDERS:
                # 範本是「在 <你的專案> 找…」，換成「在「專案」找…」，不留多餘的空白
                text = re.sub(rf"\s*{re.escape(mark)}\s*", lambda _: f"「{names[key]}」", text)
            items.append({"id": s["id"], "text": text})
        out[slot["id"]] = items
    return out or None


def render_files(a, slots, today):
    files = {"AGENTS.md": render_rules(a, today)}
    scenarios = render_scenarios(a, slots)
    if scenarios:
        doc = {"scenarios": scenarios}
        errors = validate.schema_errors(validate.validator("scenarios.schema.json"), doc, Path("scenarios.yaml"))
        if errors:
            raise SystemExit("產生的情境不符合格式（這是 profile_new.py 的錯）：\n" + "\n".join(errors))
        dumped = yaml.safe_dump(doc, allow_unicode=True, sort_keys=False, width=10000)
        files["scenarios.yaml"] = TEXT[a["language"]]["scenarios_note"].format(name=a["name"], date=today) + dumped
    files["answers.json"] = json.dumps(a, ensure_ascii=False, indent=2) + "\n"
    return files


def blocked(data, state, name, force, tracked=None):
    """不能寫的原因；可以寫就回傳 None。寫的位置是 repo 外的 state/profiles/<名稱>。"""
    in_repo, folder = data / "profiles" / name, state / "profiles" / name
    if in_repo.exists():
        if name in profiles.legacy(data, tracked) and not folder.exists():
            return (f"repo 裡有舊版存的同名 profile（{in_repo}）：先搬到 repo 外再重新訪談，"
                    f"uv run engine/scripts/profiles.py --migrate（刪掉 repo 裡的舊檔前會先問）")
        if not folder.exists():
            return f"repo 裡已經有 profile「{name}」（data/profiles/{name}，default 或維護者手寫的），不會覆蓋；請換一個名稱。"
    if not folder.exists():
        return None
    if not (folder / "answers.json").exists():
        return f"{folder} 是手寫的 profile（沒有 answers.json），不會覆蓋；請換一個名稱。"
    if not force:
        return f"{folder} 已經存在；要用新答案覆蓋就加 --force，舊檔會先備份成 .bak。"
    return None


def write_profile(folder, files):
    """寫入新檔；同名舊檔先改名成 .bak（已經有 .bak 就加時間）。回傳備份檔。"""
    folder.mkdir(parents=True, exist_ok=True)
    backups = []
    for name in ("AGENTS.md", "scenarios.yaml", "answers.json"):
        old = folder / name
        if old.exists():
            bak = folder / f"{name}.bak"
            if bak.exists():
                bak = folder / f"{name}.bak-{datetime.now():%Y%m%d%H%M%S}"
            old.replace(bak)
            backups.append(bak)
    for name, text in files.items():
        (folder / name).write_bytes(text.encode("utf-8"))
    return backups


def apply_real(name):
    # 第 5 題答「不要」就不裝 omnikit-eval：規則接上之後，skills 也照這份 profile 同步
    return profiles.apply(profiles.DATA, profiles.STATE, wanted=name) + profiles.sync_skills()


def run(answers_path, data, state=None, write=False, apply=False, force=False, apply_fn=apply_real, today=None,
        tracked=None):
    state = STATE if state is None else state
    try:
        answers = json.loads(Path(answers_path).read_text(encoding="utf-8-sig"))
    except (OSError, ValueError) as e:
        print(f"讀不到答案檔 {answers_path}：{e}")
        return 1
    errors = check_answers(answers) if isinstance(answers, dict) else ["答案檔的最外層要是 JSON 物件"]
    if errors:
        print("答案有問題，請重新確認：")
        print("\n".join(f"- {e}" for e in errors))
        return 1
    a = normalize(answers)
    slots = validate.load_yaml(data / "slots.yaml")["slots"]
    files = render_files(a, slots, today or date.today().isoformat())
    folder = state / "profiles" / a["name"]
    problem = blocked(data, state, a["name"], force, tracked)

    if not write:
        print(f"預覽：會在 {folder}（repo 外，不會被 commit）寫入 {'、'.join(files)}")
        for name, text in files.items():
            if name != "answers.json":
                print(f"\n----- {name} -----\n{text.rstrip()}")
        skip = {s: why for s, (key, why) in profiles.OPTIONAL_SKILLS.items() if a.get(key) is False}
        if skip:
            print(f"\n套用時不裝 {'、'.join(skip)}（選了{'、'.join(dict.fromkeys(skip.values()))}）；已經裝了的會拿掉。")
        if problem:
            print(f"\n不能寫入：{problem}")
            return 1
        print("\n這是預覽，還沒寫檔。確認後加 --write；要同時套用再加 --apply。")
        return 0

    if problem:
        print(f"不能寫入：{problem}")
        return 1
    backups = write_profile(folder, files)
    print(f"已寫入 {folder}：{'、'.join(files)}")
    if backups:
        print(f"舊檔備份成：{'、'.join(b.name for b in backups)}")
    errors, _ = validate.check(data, profile=a["name"], state=state)
    if errors:
        print("名冊驗證失敗：")
        print("\n".join(f"- {e}" for e in errors))
        return 1
    if apply:
        for line in apply_fn(a["name"]):
            print(line)
    else:
        print(f"要套用：uv run engine/scripts/profiles.py --set {a['name']}")
    return 0


